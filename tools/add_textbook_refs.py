def build_ref(vol_key, units, specials, note):
    tb = json.loads((C / "textbook.json").read_text(encoding="utf-8"))
    vol = tb["volumes"][vol_key]
    unit_nums = []
    for no in units:
        name = vol["units"].get(str(no))
        if name is None:
            raise KeyError(f"{vol_key} 没有第 {no} 单元")
        unit_nums.append({"no": no, "name": name})
    sp = []
    for s in specials:
        if s in vol["practical"]:
            sp.append({"kind": "综合与实践", "name": s})
        elif s in vol["corner"]:
            sp.append({"kind": "数学广角", "name": s})
        else:
            raise KeyError(f"{vol_key} 没有栏目「{s}」")
    return {
        "volume": vol_key,
        "volume_label": vol["label"],
        "units": unit_nums,
        "special": sp,
        "note": note,
    }


def merge_refs(refs, note):
    """把多册定位合并成一个 textbook_ref：units 与 special 各自汇总。"""
    out = {"note": note, "locations": []}
    for r in refs:
        out["locations"].append({
            "volume": r["volume"],
            "volume_label": r["volume_label"],
            "units": r["units"],
            "special": r["special"],
        })
    return out


def main():
    tb = json.loads((C / "textbook.json").read_text(encoding="utf-8"))
    n = 0
    for pid, (note, places) in LOC.items():
        p = C / "points" / f"{pid}.json"
        if not p.exists():
            print(f"  !! 篇目不存在，跳过：{pid}")
            continue
        d = json.loads(p.read_text(encoding="utf-8"))
        ref = merge_refs([build_ref(v, u, sp, "") for v, u, sp in places], note)
        d["textbook_ref"] = ref
        # meta.source 同步成结构化描述
        parts = []
        for loc in ref["locations"]:
            seg = [loc["volume_label"]]
            for u in loc["units"]:
                seg.append(f"第{u['no']}单元 {u['name']}")
            for sp in loc["special"]:
                seg.append(f"{sp['kind']}·{sp['name']}")
            parts.append("、".join(seg))
        src = d.get("meta", {}).get("source", "")
        head = src.split("／")[0].strip()
        d.setdefault("meta", {})["source"] = f"{head} ／ 人教版2024 {'、'.join(parts)}"
        p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
        n += 1
    print(f"已写入 {n} 篇的 textbook_ref")


if __name__ == "__main__":
    main()
