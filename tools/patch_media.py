def size_of(name):
    s = open(os.path.join(MEDIA, name), encoding="utf-8").read(600)
    m = re.search(r'width="(\d+)"\s+height="(\d+)"', s)
    if not m:
        raise RuntimeError("读不到尺寸: " + name)
    return int(m.group(1)), int(m.group(2))


def save(path, d):
    with open(path, "w", encoding="utf-8") as fp:
        json.dump(d, fp, ensure_ascii=False, indent=2)
        fp.write("\n")


def main():
    done = updated = 0
    for pid, (name, alt, caption) in DATA.items():
        path = os.path.join(POINTS, pid + ".json")
        if not os.path.isfile(path):
            raise RuntimeError("知识点不存在: " + pid)
        if not os.path.isfile(os.path.join(MEDIA, name)):
            raise RuntimeError("配图不存在: " + name)
        with open(path, encoding="utf-8") as fp:
            d = json.load(fp)
        w, h = size_of(name)
        item = {"id": "fig1", "file": name, "alt": alt,
                "width": w, "height": h, "caption": caption}
        if d.get("media"):
            hit = False
            for m in d["media"]:
                if m.get("file") == name:
                    m.update(width=w, height=h, alt=alt, caption=caption)
                    hit = True
            if not hit:
                raise RuntimeError(f"{pid} 已有 media 但文件名不符: "
                                   f"{[m.get('file') for m in d['media']]}")
            save(path, d)
            updated += 1
            continue
        out = {}
        for k, v in d.items():
            if k == "sections":
                out["media"] = [item]
            out[k] = v
        if "media" not in out:
            out["media"] = [item]
        save(path, out)
        done += 1
    print(f"新增 media 引用: {done}，更新已有引用: {updated}，共 {len(DATA)}")


if __name__ == "__main__":
    main()
